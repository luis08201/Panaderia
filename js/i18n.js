export function t(key, vars = {}) {
  const table = getLang() === "es" ? ES : EN;
  let value = table[key] ?? EN[key] ?? key;
  for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, replacement ?? "");
  return value;
}

export function applyDom(root = document) {
  const lang = getLang();
  rememberLang(lang);
  document.documentElement.lang = lang === "es" ? "es" : "en";
  const locale = document.querySelector('meta[property="og:locale"]');
  if (locale) locale.setAttribute("content", lang === "es" ? "es_NI" : "en_US");
  for (const element of root.querySelectorAll("[data-i18n]")) {
    const key = element.dataset.i18n;
    if (key.endsWith(".html")) element.innerHTML = t(key);
    else element.textContent = t(key);
  }
  for (const element of root.querySelectorAll("[data-i18n-aria]")) element.setAttribute("aria-label", t(element.dataset.i18nAria));
  for (const element of root.querySelectorAll("[data-i18n-placeholder]")) element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  for (const button of root.querySelectorAll("[data-set-lang]")) {
    button.setAttribute("aria-pressed", String(button.dataset.setLang === lang));
  }
}

export function initLanguage() {
  applyDom();
  document.addEventListener("click", (event) => {
    const button = event.target.closest("[data-set-lang]");
    if (!button || button.dataset.setLang === getLang()) return;
    rememberLang(button.dataset.setLang);
    const url = new URL(location.href);
    url.searchParams.delete("lang");
    if (button.dataset.setLang === "es") url.searchParams.set("lang", "es");
    location.assign(url);
  });
}
